function V = reconstruction_check(robot, variant)
%RECONSTRUCTION_CHECK Exact check that the extracted regressor reproduces the input torques.
%
%   V = reconstruction_check('UR5e', 'known_geometry')
%
% Proves, for all joint states, that  tau_sym(x, rho) - A(x)*Theta(rho) = 0,
% where tau_sym are the symbolic torque equations supplied to the regrouping,
% A the extracted common regressor and Theta the extracted monomials (Stages 1-2).
% The residual of every joint is expanded, sin(q_k), cos(q_k) and sign(qd_k)
% are replaced by the independent variables s_k, c_k and g_k, and the
% polynomial is reduced modulo the ideal generated by s_k^2 + c_k^2 - 1
% (a Groebner basis, see exact_verification.m). The physical symbols stay
% polynomial variables. A zero remainder in every joint proves the identity.
% Together with the dependency certificate of exact_verification.m this proves
%   tau_sym = A*Theta = A_b*Theta_b   (Eq. complete certificate of the paper).
%
%   robot   'UR5e' or 'IRB120'
%   variant 'results' (symbolic dimensions), 'known_geometry', 'actuation',
%           'actuation_known_geometry'
% The torque preparation replicates regroup_base_parameters.m exactly.
% Writes reconstruction_check.txt to the results folder of the variant.

    here = fileparts(mfilename('fullpath'));
    rob  = fullfile(fileparts(here), robot);
    addpath(rob);
    nDOF = 6;
    switch robot
        case 'UR5e'
            gn = {'L1','L2','L3','L4','L5','L6','LL1','LL2'};
            gv = [0.1625 0.425 0.3922 -0.1333 -0.0997 -0.0996 0 0];
        case 'IRB120'
            gn = {'L1','L2','L3','L4','L5','L6'};
            gv = [0.29 0.27 0.07 0.302 0.072 0];
        otherwise
            error('Unsupported robot %s', robot);
    end
    known = any(strcmp(variant, {'known_geometry', 'actuation_known_geometry'}));
    act   = any(strcmp(variant, {'actuation', 'actuation_known_geometry'}));
    if strcmp(variant, 'results'), rfolder = fullfile(rob, 'results'); else, rfolder = fullfile(rob, 'results', variant); end

    t0 = tic;
    torques = load_torque_equations(fullfile(rob, 'torque_equations'), nDOF);
    qn   = arrayfun(@(k) sym(sprintf('t%d',   k), 'real'), 1:nDOF);
    qdn  = arrayfun(@(k) sym(sprintf('t%dd',  k), 'real'), 1:nDOF);
    qddn = arrayfun(@(k) sym(sprintf('t%ddd', k), 'real'), 1:nDOF);
    for jn = 1:nDOF
        if known, torques{jn} = subs(torques{jn}, sym(gn), sym(gv)); end
        if act
            Ia = sym(sprintf('Ia%d', jn), 'real');  Fv = sym(sprintf('Fv%d', jn), 'real');
            Fc = sym(sprintf('Fc%d', jn), 'real');
            torques{jn} = torques{jn} + Ia*qddn(jn) + Fv*qdn(jn) + Fc*sign(qdn(jn));
        end
    end
    S = load(fullfile(rfolder, 'base_regressor.mat'), 'A_matrix_common', 'theta_common');
    A = S.A_matrix_common;  th = S.theta_common(:);

    s  = arrayfun(@(k) sym(sprintf('s%d', k), 'real'), 1:nDOF);
    c  = arrayfun(@(k) sym(sprintf('c%d', k), 'real'), 1:nDOF);
    sg = arrayfun(@(k) sym(sprintf('g%d', k), 'real'), 1:nDOF);
    ideal = s.^2 + c.^2 - 1;
    bad = 0;  nE = nDOF;  nterms = zeros(1, nDOF);
    for jn = 1:nDOF
        Rj = expand(torques{jn} - A(jn, :)*th);
        Rj = subs(Rj, [sin(qn) cos(qn) sign(qdn)], [s c sg]);
        if any(has(Rj, [qn, sign(qdn)]))
            error('Unsupported functions remain after expansion (joint %d).', jn);
        end
        nterms(jn) = numel(children(Rj));
        if isequal(Rj, sym(0)), continue; end
        vars = [s c setdiff(symvar(Rj), [s c])];
        r = polynomialReduce(Rj, ideal, vars, 'MonomialOrder', 'lexicographic');
        if ~isequal(expand(r), sym(0)), bad = bad + 1; end
    end
    V = struct('robot', robot, 'variant', variant, 'joints', nE, 'nonzero', bad, ...
        'certified', bad == 0, 'run_time_s', toc(t0));

    fid = fopen(fullfile(rfolder, 'reconstruction_check.txt'), 'w');
    fprintf(fid, 'Robot / variant                        : %s / %s\n', robot, variant);
    fprintf(fid, 'Joint residuals tau_sym - A*Theta      : %d\n', nE);
    fprintf(fid, 'Joint residuals with nonzero remainder : %d\n', bad);
    fprintf(fid, 'Reconstruction certified exactly       : %d\n', bad == 0);
    fprintf(fid, 'Run time                               : %.1f s\n', V.run_time_s);
    fclose(fid);
    fprintf('%s / %s: %d of %d joint residuals nonzero, certified = %d (%.1f s)\n', ...
        robot, variant, bad, nE, bad == 0, V.run_time_s);
end
