function V = exact_verification(results_folder)
%EXACT_VERIFICATION Exact certificate of the regrouping A_D = A_I*Gamma.
%
%   V = exact_verification(results_folder)
%
% Gamma is computed in floating point by regroup_base_parameters.m. Exact
% candidates for its entries are generated in turn and accepted only if the
% identity A_D(x) - A_I(x)*Gamma_ex = 0 is then proved for all x:
%   1) finite decimals (rounding to twelve decimals), which recover the
%      coefficients exactly when the link dimensions are given in decimal form;
%   2) rationals from continued fractions (relative tolerance 1e-12), which
%      recover coefficients such as 1/3 that have no finite decimal form.
% The identity is proved by expanding every entry, replacing sin(q_k),
% cos(q_k) and sign(qd_k) by the independent variables s_k, c_k and g_k,
% and reducing the polynomial modulo the ideal generated by
% s_k^2 + c_k^2 - 1 (k = 1..n). These generators have pairwise coprime
% leading terms in lexicographic order and therefore form a Groebner basis;
% the remainder is zero if and only if the entry vanishes identically.
% Treating g_k as free variables is conservative: an identity in free g_k
% holds in particular for g_k = sign(qd_k).
% If no candidate passes, the regrouping keeps its numerical verification
% only (V.certified = false). Writes exact_verification.txt to results_folder.
%
% The certificate covers the equivalence A*Theta = A_b*Theta_b. The rank
% (minimality) is determined numerically in Stage 3.

    t0 = tic;
    S = load(fullfile(results_folder, 'base_regressor.mat'), 'A_matrix_common', ...
        'independent_cols', 'dependent_cols', 'Gamma');
    A = S.A_matrix_common;  ind = S.independent_cols;  dep = S.dependent_cols;
    G = S.Gamma;  n = size(A, 1);
    V = struct('n_dependent', numel(dep), 'candidate', 'none needed', 'max_candidate_error', 0, ...
        'n_entries', 0, 'n_nonzero_remainders', 0, 'certified', true, 'run_time_s', 0);
    if isempty(dep)
        V.run_time_s = toc(t0);  write_report(results_folder, V);  return
    end

    candidates = {'finite decimals (12 decimals)', @(g) sym(round(g*1e12))/sym(10)^12;
                  'continued-fraction rationals', @rational_candidate};
    for c = 1:size(candidates, 1)
        Gr = candidates{c, 2}(G);
        [nE, bad] = remainders(A, ind, dep, Gr, n);
        V.candidate = candidates{c, 1};
        V.max_candidate_error = max(abs(double(Gr(:)) - G(:)));
        V.n_entries = nE;  V.n_nonzero_remainders = bad;
        if bad == 0, break; end
    end
    V.certified = (V.n_nonzero_remainders == 0);
    if ~V.certified, V.candidate = 'none (numerical verification only)'; end
    V.run_time_s = toc(t0);
    write_report(results_folder, V);
end

function Gr = rational_candidate(G)
    Gr = sym(zeros(size(G)));
    for k = 1:numel(G)
        if G(k) ~= 0
            [num, den] = rat(G(k), 1e-12*max(1, abs(G(k))));
            Gr(k) = sym(num)/sym(den);
        end
    end
end

function [nE, bad] = remainders(A, ind, dep, Gr, n)
    qn  = arrayfun(@(k) sym(sprintf('t%d', k), 'real'), 1:n);
    qdn = arrayfun(@(k) sym(sprintf('t%dd', k), 'real'), 1:n);
    s  = arrayfun(@(k) sym(sprintf('s%d', k), 'real'), 1:n);
    c  = arrayfun(@(k) sym(sprintf('c%d', k), 'real'), 1:n);
    sg = arrayfun(@(k) sym(sprintf('g%d', k), 'real'), 1:n);
    E = expand(A(:, dep) - A(:, ind)*Gr);
    E = subs(E, [sin(qn) cos(qn) sign(qdn)], [s c sg]);
    if any(has(E(:), [qn, sign(qdn)]))
        error('Unsupported functions remain after expansion; the identity is outside the certified class.');
    end
    vars = [s c setdiff(symvar(E), [s c])];
    ideal = s.^2 + c.^2 - 1;
    nE = numel(E);  bad = 0;
    for k = 1:nE
        if isequal(E(k), sym(0)), continue; end
        r = polynomialReduce(E(k), ideal, vars, 'MonomialOrder', 'lexicographic');
        if ~isequal(expand(r), sym(0)), bad = bad + 1; end
    end
end

function write_report(folder, V)
    fid = fopen(fullfile(folder, 'exact_verification.txt'), 'w');
    fprintf(fid, 'Dependent columns                      : %d\n', V.n_dependent);
    fprintf(fid, 'Exact coefficient candidate            : %s\n', V.candidate);
    fprintf(fid, 'Max |Gamma_candidate - Gamma_float|    : %.3e\n', V.max_candidate_error);
    fprintf(fid, 'Entries of A_D - A_I*Gamma checked     : %d\n', V.n_entries);
    fprintf(fid, 'Entries with nonzero remainder         : %d\n', V.n_nonzero_remainders);
    fprintf(fid, 'Equivalence certified exactly          : %d\n', V.certified);
    fprintf(fid, 'Run time                               : %.1f s\n', V.run_time_s);
    fclose(fid);
    type(fullfile(folder, 'exact_verification.txt'));
end
