function write_nominal_file(fname, tag, robot_name, P, geom)
%WRITE_NOMINAL_FILE Write nominal_parameters_<tag>.m from extracted link data.
    fid = fopen(fname, 'w');
    w = @(varargin) fprintf(fid, varargin{:});
    w('function [names, values, centroidal] = nominal_parameters_%s()\n', tag);
    w('%%NOMINAL_PARAMETERS_%s Nominal parameters of the %s Simscape model.\n', upper(tag), tag);
    w('%%\n%%   [names, values] = nominal_parameters_%s() returns symbol names and\n', tag);
    w('%%   numerical values for every symbol that can appear in theta_base of the\n');
    w('%%   ORIGIN-REFERENCED (parallel-axis) model: m_i, Lc_ix/y/z (centre of mass\n');
    w('%%   in MDH frame {i}), link dimensions, and Ixx_i..Iyz_i = inertia about the\n');
    w('%%   ORIGIN of MDH frame {i}.\n%%\n');
    w('%%   GENERATED by simulink/generate_identification_data.m from\n');
    w('%%   panda_robot.m (loadrobot(''%s'') with the inertial parameters of\n', robot_name);
    w('%%   Gaz et al., IEEE RA-L 2019); do not edit by hand.\n');
    w('%%   The centroidal values are expressed in the MDH link frames; the\n');
    w('%%   origin-referenced tensor follows from I_o = I_c + m (c''c E3 - c c'').\n\n');
    w('    c.m  = %s;\n', mat2str(P.m, 10));
    gn = fieldnames(geom);
    for k = 1:numel(gn), w('    c.%s = %s;\n', gn{k}, mat2str(geom.(gn{k}), 10)); end
    w('    %% centre of mass [x y z] of link i in MDH frame {i} (m)\n');
    w('    c.Lc = %s;\n', mat2str(P.Lc, 10));
    w('    %% centroidal inertia [Ixx Iyy Izz Ixy Ixz Iyz] (kg m^2), MDH frame {i} axes\n');
    w('    c.Ic = %s;\n', mat2str(P.Ic, 10));
    w('    centroidal = c;\n\n');
    w('    names = {};  values = [];\n');
    w('    for i = 1:%d\n', numel(P.m));
    w('        Ic = [c.Ic(i,1) c.Ic(i,4) c.Ic(i,5); c.Ic(i,4) c.Ic(i,2) c.Ic(i,6); c.Ic(i,5) c.Ic(i,6) c.Ic(i,3)];\n');
    w('        p  = c.Lc(i,:).'';\n');
    w('        Io = Ic + c.m(i)*((p.''*p)*eye(3) - p*p.'');      %% parallel-axis theorem\n');
    w('        names  = [names, {sprintf(''m%%d'',i), sprintf(''Lc%%dx'',i), sprintf(''Lc%%dy'',i), sprintf(''Lc%%dz'',i), ...\n');
    w('                  sprintf(''Ixx%%d'',i), sprintf(''Iyy%%d'',i), sprintf(''Izz%%d'',i), ...\n');
    w('                  sprintf(''Ixy%%d'',i), sprintf(''Ixz%%d'',i), sprintf(''Iyz%%d'',i)}]; %%#ok<AGROW>\n');
    w('        values = [values, c.m(i), c.Lc(i,:), Io(1,1), Io(2,2), Io(3,3), Io(1,2), Io(1,3), Io(2,3)]; %%#ok<AGROW>\n');
    w('    end\n');
    w('    names  = [names, {%s, ''g''}];\n', strjoin(cellfun(@(s) ['''' s ''''], gn.', 'UniformOutput', false), ', '));
    w('    values = [values, %s, 9.81];\n', strjoin(cellfun(@(s) ['c.' s], gn.', 'UniformOutput', false), ', '));
    w('end\n');
    fclose(fid);
end
